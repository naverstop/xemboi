def _stem_ko(s: str) -> str:
    return f"{stem_korean(s)}({s})"


def compute_johu_yongsin(day_stem: str, month_branch: str) -> JohuYongsin:
    """일간·월지 → 궁통보감 조후용신(결정적). 표에 없는 입력이면 KeyError."""
    primary, supporting = JOHU_TABLE[day_stem][month_branch]
    season, clim_desc, priority = _SEASON[month_branch]
    mb_ko = BRANCH_KOREAN[EARTHLY_BRANCHES.index(month_branch)]

    if priority:
        note = (
            f"{mb_ko}({month_branch})월은 {clim_desc} 시기라 조후(한난 조절)를 가장 먼저 봅니다. "
            f"그래서 {_stem_ko(primary)}을(를) 우선 조후용신으로 봅니다."
        )
    else:
        note = (
            f"{mb_ko}({month_branch})월은 {clim_desc} 환절기라 한난이 비교적 온화합니다. "
            f"조후용신 {_stem_ko(primary)}을(를) 참고하되 억부·격국을 함께 봅니다."
        )

    climate = "寒(겨울)" if season == "겨울" else "暖(여름)" if season == "여름" else "평(환절기)"
    return JohuYongsin(
        primary=primary,
        supporting=list(supporting),
        season=season,
        climate=climate,
        is_climate_priority=priority,
        note=note,
        source="궁통보감 조후용신(阿部泰山 조후용신간법)",
    )


def _table_is_complete() -> bool:
    """120칸(10천간×12월) 정용신이 모두 유효한 천간인지 — 임포트 시 자가검증용."""
    if len(JOHU_TABLE) != 10:
        return False
    for stem, months in JOHU_TABLE.items():
        if set(months) != set(JOHU_MONTHS):
            return False
        for primary, _sup in months.values():
            if primary not in STEM_TO_WUXING:
                return False
    return True
