def is_business_day(d: date) -> bool:
    """영업일 = 평일이면서 법정공휴일 아님."""
    if d.weekday() >= 5:                        # 토(5)·일(6)
        return False
    return d.strftime("%m-%d") not in _HOLIDAYS.get(d.year, set())


def last_business_day(year: int, month: int) -> date:
    """해당 월의 마지막 영업일 — 지급예정일(운영자 확정: 당월 마지막 영업일 송금)."""
    if month == 12:
        d = date(year, 12, 31)
    else:
        d = date(year, month + 1, 1) - timedelta(days=1)
    while not is_business_day(d):
        d -= timedelta(days=1)
    return d


def cycle_of(dt: datetime) -> str:
    """세션 발생 시각(UTC 저장분은 호출부에서 KST 보정) → 소속 정산월 'YYYY-MM'.
    26일 00:00부터는 다음 달 정산분(25일 24시 마감)."""
    y, m = dt.year, dt.month
    if dt.day >= 26:
        m += 1
        if m > 12:
            m, y = 1, y + 1
    return f"{y:04d}-{m:02d}"


def cycle_window(cycle: str) -> tuple[datetime, datetime]:
    """정산월 'YYYY-MM' → 실적창 [시작, 끝) — (M-1)월 26일 00:00 ~ M월 26일 00:00."""
    y, m = int(cycle[:4]), int(cycle[5:7])
    end = datetime(y, m, 26)
    if m == 1:
        start = datetime(y - 1, 12, 26)
    else:
        start = datetime(y, m - 1, 26)
    return start, end


def payout_date(cycle: str) -> date:
    """정산월 'YYYY-MM'의 지급예정일 = 당월 마지막 영업일."""
    y, m = int(cycle[:4]), int(cycle[5:7])
    return last_business_day(y, m)
